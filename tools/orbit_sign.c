/* orbit-sign: offline release signing for ORBIT updates (runs on the developer's PC only).
 *
 *   orbit-sign keygen <keydir>             new release key; refuses to overwrite an existing one.
 *                                          Writes <keydir>/orbit-release.key (secret, never print or
 *                                          commit it) and <keydir>/orbit-release.pub (hex).
 *   orbit-sign header <keydir> <out.h>      write the public key as include/update_key.h
 *   orbit-sign hash <file>                  print "<size> <blake2b-256 hex>"
 *   orbit-sign sign <keydir> <payload.json> <out-manifest.json>
 *                                          sign the exact payload bytes and write the manifest
 *
 * The tool never uploads anything; publishing a manifest is a separate, manual step. */
#include "cJSON.h"
#include "monocypher.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/stat.h>

static int read_all(const char *path, unsigned char **out, size_t *n) {
    FILE *f = fopen(path, "rb");
    if (!f)
        return -1;
    size_t cap = 1 << 16, len = 0;
    unsigned char *b = malloc(cap);
    size_t k;
    while (b && (k = fread(b + len, 1, cap - len, f)) > 0) {
        len += k;
        if (len == cap) {
            unsigned char *nb = realloc(b, cap *= 2);
            if (!nb) {
                free(b);
                b = NULL;
            }
            b = nb;
        }
    }
    fclose(f);
    if (!b)
        return -1;
    *out = b;
    *n = len;
    return 0;
}
static void hex(char *out, const uint8_t *in, size_t n) {
    for (size_t i = 0; i < n; i++)
        sprintf(out + 2 * i, "%02x", in[i]);
}
static int load_secret(const char *dir, uint8_t secret[64]) {
    char path[1024];
    snprintf(path, sizeof(path), "%s/orbit-release.key", dir);
    FILE *f = fopen(path, "rb");
    int ok = f && fread(secret, 1, 64, f) == 64;
    if (f)
        fclose(f);
    return ok ? 0 : -1;
}
int main(int argc, char **argv) {
    if (argc == 3 && !strcmp(argv[1], "keygen")) {
        char key[1024], pub[1024];
        snprintf(key, sizeof(key), "%s/orbit-release.key", argv[2]);
        snprintf(pub, sizeof(pub), "%s/orbit-release.pub", argv[2]);
        FILE *exists = fopen(key, "rb");
        if (exists) {
            fclose(exists);
            fprintf(stderr, "a release key already exists in %s - not overwritten\n", argv[2]);
            return 1;
        }
        mkdir(argv[2], 0700);
        uint8_t seed[32], secret[64], public_key[32];
        FILE *r = fopen("/dev/urandom", "rb");
        if (!r || fread(seed, 1, 32, r) != 32)
            return 1;
        fclose(r);
        crypto_eddsa_key_pair(secret, public_key, seed);
        FILE *f = fopen(key, "wb");
        if (!f || fwrite(secret, 1, 64, f) != 64 || fclose(f))
            return 1;
        chmod(key, 0600);
        crypto_wipe(secret, 64);
        char h[65];
        hex(h, public_key, 32);
        f = fopen(pub, "w");
        if (!f)
            return 1;
        fprintf(f, "%s\n", h);
        fclose(f);
        printf("public key: %s\n", h);
        return 0;
    }
    if (argc == 4 && !strcmp(argv[1], "header")) {
        uint8_t secret[64];
        if (load_secret(argv[2], secret))
            return fprintf(stderr, "no release key in %s\n", argv[2]), 1;
        uint8_t public_key[32];
        memcpy(public_key, secret + 32, 32); /* monocypher: secret = seed || public key */
        crypto_wipe(secret, 64);
        FILE *f = fopen(argv[3], "w");
        if (!f)
            return 1;
        fprintf(f, "/* ORBIT release public key (generated by tools/orbit_sign.c). Only the public\n"
                   " * half is here; the secret key stays on the developer's PC. */\n"
                   "#define UPDATE_PUBLIC_KEY {");
        for (int i = 0; i < 32; i++)
            fprintf(f, "%s0x%02x", i ? ", " : "", public_key[i]);
        fprintf(f, "}\n");
        return fclose(f) ? 1 : 0;
    }
    if (argc == 3 && !strcmp(argv[1], "hash")) {
        unsigned char *b;
        size_t n;
        if (read_all(argv[2], &b, &n))
            return 1;
        uint8_t h[32];
        crypto_blake2b(h, 32, b, n);
        char s[65];
        hex(s, h, 32);
        printf("%zu %s\n", n, s);
        free(b);
        return 0;
    }
    if (argc == 5 && !strcmp(argv[1], "sign")) {
        uint8_t secret[64], sig[64];
        unsigned char *payload;
        size_t n;
        if (load_secret(argv[2], secret))
            return fprintf(stderr, "no release key in %s\n", argv[2]), 1;
        if (read_all(argv[3], &payload, &n))
            return 1;
        while (n && (payload[n - 1] == '\n' || payload[n - 1] == '\r'))
            n--;
        payload[n] = 0; /* buffer is always larger than the data */
        cJSON *check = cJSON_Parse((char *)payload);
        if (!check)
            return fprintf(stderr, "payload is not valid JSON\n"), 1;
        cJSON_Delete(check);
        crypto_eddsa_sign(sig, secret, payload, n);
        crypto_wipe(secret, 64);
        char s[129];
        hex(s, sig, 64);
        cJSON *m = cJSON_CreateObject();
        cJSON_AddStringToObject(m, "payload", (char *)payload);
        cJSON_AddStringToObject(m, "sig", s);
        char *out = cJSON_PrintUnformatted(m);
        FILE *f = fopen(argv[4], "w");
        if (!out || !f || fputs(out, f) < 0 || fclose(f))
            return 1;
        printf("signed %zu payload bytes -> %s\n", n, argv[4]);
        return 0;
    }
    fprintf(stderr, "usage: orbit-sign keygen <dir> | header <dir> <out.h> | hash <file> | "
                    "sign <dir> <payload.json> <manifest.json>\n");
    return 2;
}
